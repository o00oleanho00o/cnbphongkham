def test_loc_ky_tu_an_u_1d41d_khong_bi_loc_vi_doi_nghia_cong_thuc_toan() -> None:
    """U+1D41D (Mathematical Bold Small D) KHÔNG bị lọc - đã loại khỏi bộ lọc vì đổi NGHĨA công thức toán"""
